import * as path from 'node:path'
import { afterEach, describe, expect, it } from 'vitest'
import { rustDetector } from '../src/detectors/rust.js'
import { cleanup, makeProject } from './helpers.js'

const dirs: string[] = []
const project = async (files: Record<string, string>) => {
  const dir = await makeProject(files)
  dirs.push(dir)
  return dir
}
afterEach(async () => {
  await Promise.all(dirs.splice(0).map(cleanup))
})

const member = async (files: Record<string, string>, rel: string) => {
  const root = await project(files)
  return rustDetector.detect({ dir: path.join(root, rel), boundary: root })
}

describe('rustDetector', () => {
  it('returns undefined without Cargo.toml', async () => {
    const dir = await project({ 'src/main.rs': 'fn main() {}' })
    expect(await rustDetector.detect({ dir })).toBeUndefined()
  })

  it('reads a single package', async () => {
    const dir = await project({
      'Cargo.toml': '[package]\nname = "ripgrep"\nversion = "14.1.1"\nedition = "2021"\nrust-version = "1.72"\n',
      'Cargo.lock': '# This file is automatically @generated by Cargo.\nversion = 4\n',
    })
    expect(await rustDetector.detect({ dir })).toEqual({
      language: 'rust',
      name: 'ripgrep',
      version: '14.1.1',
      versionSource: 'Cargo.toml:package.version',
      packageManager: 'cargo',
      packageManagerVersion: '',
      languageVersion: '1.72',
      languageVersionSource: 'Cargo.toml:package.rust-version',
      languageVersionFile: '',
      manifest: 'Cargo.toml',
      lockfile: 'Cargo.lock',
      workspaceRoot: '.',
      installCommand: 'cargo fetch --locked',
      cacheDependencyPath: 'Cargo.lock',
    })
  })

  it('fetches without --locked when there is no Cargo.lock (libraries)', async () => {
    const dir = await project({ 'Cargo.toml': '[package]\nname = "lib"\nversion = "0.1.0"\n' })
    expect(await rustDetector.detect({ dir })).toMatchObject({ lockfile: '', installCommand: 'cargo fetch', cacheDependencyPath: '' })
  })

  it('survives a malformed Cargo.toml', async () => {
    const dir = await project({ 'Cargo.toml': '[package\nname = ' })
    expect(await rustDetector.detect({ dir })).toMatchObject({ language: 'rust', name: '', version: '' })
  })

  it('falls back to release tooling when the version is omitted', async () => {
    const dir = await project({ 'Cargo.toml': '[package]\nname = "app"\npublish = false\n', '.cz.toml': '[tool.commitizen]\nversion = "0.3.0"\n' })
    expect(await rustDetector.detect({ dir })).toMatchObject({ version: '0.3.0', versionSource: '.cz.toml:tool.commitizen.version' })
  })
})

describe('rustDetector: toolchain', () => {
  it.each([
    [{ 'rust-toolchain.toml': '[toolchain]\nchannel = "1.83.0"\ncomponents = ["clippy"]\n' }, '1.83.0', 'rust-toolchain.toml:toolchain.channel', 'rust-toolchain.toml'],
    [{ 'rust-toolchain': 'nightly-2025-06-01\n' }, 'nightly-2025-06-01', 'rust-toolchain', 'rust-toolchain'],
    [{ 'rust-toolchain': '[toolchain]\nchannel = "stable"\n' }, 'stable', 'rust-toolchain:toolchain.channel', 'rust-toolchain'],
    [{ '.tool-versions': 'rust 1.80.1\n' }, '1.80.1', '.tool-versions', ''],
    [{ 'mise.toml': '[tools]\nrust = "1.81"\n' }, '1.81', 'mise.toml:tools.rust', ''],
  ])('%j', async (files, version, source, file) => {
    const dir = await project({ 'Cargo.toml': '[package]\nname = "x"\nversion = "1.0.0"\n', ...files })
    expect(await rustDetector.detect({ dir })).toMatchObject({ languageVersion: version, languageVersionSource: source, languageVersionFile: file })
  })

  it('prefers a toolchain file over the MSRV', async () => {
    const dir = await project({
      'Cargo.toml': '[package]\nname = "x"\nversion = "1.0.0"\nrust-version = "1.70"\n',
      'rust-toolchain.toml': '[toolchain]\nchannel = "1.83.0"\n',
    })
    expect((await rustDetector.detect({ dir }))?.languageVersion).toBe('1.83.0')
  })

  // rustup resolves toolchain files by walking up, so the repository's file beats a member's MSRV.
  it('uses a toolchain file of a parent directory before the package MSRV', async () => {
    const result = await member(
      {
        'rust-toolchain.toml': '[toolchain]\nchannel = "1.84.0"\n',
        'tools/gen/Cargo.toml': '[package]\nname = "gen"\nversion = "0.1.0"\nrust-version = "1.70"\n',
      },
      'tools/gen',
    )
    expect(result).toMatchObject({
      languageVersion: '1.84.0',
      languageVersionSource: '../../rust-toolchain.toml:toolchain.channel',
      languageVersionFile: '../../rust-toolchain.toml',
    })
  })

  it('ignores a toolchain file without a channel (custom toolchain path)', async () => {
    const dir = await project({
      'Cargo.toml': '[package]\nname = "x"\nrust-version = "1.75"\n',
      'rust-toolchain.toml': '[toolchain]\npath = "/opt/rust"\n',
    })
    expect((await rustDetector.detect({ dir }))?.languageVersionSource).toBe('Cargo.toml:package.rust-version')
  })

  it('never looks above the boundary', async () => {
    const root = await project({ 'rust-toolchain.toml': '[toolchain]\nchannel = "1.84.0"\n', 'a/Cargo.toml': '[package]\nname = "a"\n' })
    expect((await rustDetector.detect({ dir: path.join(root, 'a') }))?.languageVersion).toBe('')
  })
})

describe('rustDetector: workspaces', () => {
  const workspace = {
    'Cargo.toml': `
[workspace]
resolver = "2"
members = ["crates/*"]
exclude = ["crates/legacy"]

[workspace.package]
version = "2.3.0"
rust-version = "1.80"
`,
    'Cargo.lock': 'version = 4\n',
    'crates/cli/Cargo.toml': '[package]\nname = "tool-cli"\nversion.workspace = true\nrust-version.workspace = true\n',
    'crates/core/Cargo.toml': '[package]\nname = "tool-core"\nversion = "0.9.0"\nrust-version = "1.75"\n',
    'crates/legacy/Cargo.toml': '[package]\nname = "legacy"\nversion = "0.1.0"\n',
  }

  it('inherits version and MSRV from [workspace.package] and uses the root lockfile', async () => {
    expect(await member(workspace, 'crates/cli')).toMatchObject({
      name: 'tool-cli',
      version: '2.3.0',
      versionSource: '../../Cargo.toml:workspace.package.version',
      languageVersion: '1.80',
      languageVersionSource: '../../Cargo.toml:workspace.package.rust-version',
      lockfile: '../../Cargo.lock',
      workspaceRoot: '../..',
      installCommand: 'cargo fetch --locked',
      cacheDependencyPath: '../../Cargo.lock',
    })
  })

  it('keeps a member’s own version and MSRV', async () => {
    expect(await member(workspace, 'crates/core')).toMatchObject({ version: '0.9.0', versionSource: 'Cargo.toml:package.version', languageVersion: '1.75', workspaceRoot: '../..' })
  })

  it('reports the shared version for a virtual workspace root', async () => {
    const root = await project(workspace)
    expect(await rustDetector.detect({ dir: root, boundary: root })).toMatchObject({
      name: '',
      version: '2.3.0',
      versionSource: 'Cargo.toml:workspace.package.version',
      languageVersion: '1.80',
      languageVersionSource: 'Cargo.toml:workspace.package.rust-version',
      lockfile: 'Cargo.lock',
      workspaceRoot: '.',
    })
  })

  it('treats an excluded package as standalone', async () => {
    expect(await member(workspace, 'crates/legacy')).toMatchObject({ lockfile: '', workspaceRoot: '.', installCommand: 'cargo fetch' })
  })

  it('follows an explicit package.workspace path', async () => {
    const result = await member(
      {
        'rust/Cargo.toml': '[workspace]\nmembers = []\n[workspace.package]\nversion = "5.0.0"\n',
        'rust/Cargo.lock': '',
        'tools/x/Cargo.toml': '[package]\nname = "x"\nversion.workspace = true\nworkspace = "../../rust"\n',
      },
      'tools/x',
    )
    expect(result).toMatchObject({ version: '5.0.0', versionSource: '../../rust/Cargo.toml:workspace.package.version', workspaceRoot: '../../rust', lockfile: '../../rust/Cargo.lock' })
  })

  it('does not follow package.workspace outside the boundary', async () => {
    const root = await project({ 'x/Cargo.toml': '[package]\nname = "x"\nworkspace = "../.."\n' })
    expect(await rustDetector.detect({ dir: path.join(root, 'x'), boundary: root })).toMatchObject({ workspaceRoot: '.', lockfile: '' })
  })

  it('treats a root package with [workspace] as its own workspace', async () => {
    const dir = await project({ 'Cargo.toml': '[package]\nname = "rg"\nversion = "14.0.0"\n[workspace]\nmembers = ["crates/*"]\n', 'Cargo.lock': '' })
    expect(await rustDetector.detect({ dir, boundary: dir })).toMatchObject({ name: 'rg', version: '14.0.0', workspaceRoot: '.', lockfile: 'Cargo.lock' })
  })
})
